import SwiftUI

extension Color {
    enum custom {
        static let primary = Color("LPrimary")
        static let secondary = Color("LSecoundary")
        static let background = Color("LBackground")
        static let text = Color("LText")
        static let alert = Color("LAlertColor")
    }
}
