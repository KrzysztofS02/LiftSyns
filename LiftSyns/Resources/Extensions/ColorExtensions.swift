import SwiftUI

extension Color {
    enum custom {
        static let primary = Color("PrimaryColor")
        static let secondary = Color("SecondaryColor")
        static let background = Color("BackgroundColor")
        static let text = Color("AppTextColor")
        static let alert = Color("AlertColor")
    }
}
